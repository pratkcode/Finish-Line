"""Generate a semester-by-semester recommendation toward graduation.

Two phases, both pure functions of their inputs (no database access here):

1. choose_courses: decide WHAT to take. Required ("all of these") courses
   first, then one course at a time for each remaining requirement, re-running
   the requirement evaluator after every pick so a course that fills several
   requirements isn't doubled up. Missing prerequisite chains are added.
   Requirements with no suitable catalog course get labeled placeholder slots,
   and general-elective slots fill any gap to the degree's total credits.

2. schedule: decide WHEN. The chosen courses and their prerequisites form a
   directed graph. A topological sort (Kahn's algorithm) orders it and detects
   cycles; then each term takes the ready courses with the longest chain of
   dependents first (critical path), required before elective, within the
   credit limit, respecting credit-standing restrictions.

This is a planning aid, not an official UMD schedule: course offerings,
seat availability and permissions aren't known.
"""

import math
from dataclasses import dataclass

from app import terms

from app.degree_progress import REPORTED, add_reported_credits, summarize
from app.prerequisites import Checker, PrereqGraph
from app.evaluator import evaluate, walk
from app.restrictions import Rules  # re-exported for callers and tests

PLACEHOLDER_CREDITS = 3  # assumed size of a "choose a course" slot
EXTRA_TERMS = 10  # how far past the theoretical minimum to keep trying
MAX_TERMS = 80

DISCLAIMER = (
    "This is a planning recommendation generated by Finish Line, not an official UMD "
    "schedule or degree audit. Course offerings come from recent Testudo terms and can "
    "change; seats and permissions aren't known. Confirm your plan with an advisor."
)


# --- Terms -------------------------------------------------------------------------

next_term = terms.next_term  # re-exported: Fall/Spring by default


@dataclass
class Calendar:
    """Which terms a recommendation uses, and how many credits each can hold."""

    max_credits: int  # Fall and Spring
    summer_credits: int | None = None  # None: recommendations don't use Summer

    @property
    def seasons(self) -> tuple[str, ...]:
        return ("Spring", "Summer", "Fall") if self.summer_credits else ("Spring", "Fall")

    def capacity(self, term: str) -> int:
        season, _ = terms.parse(term)
        if season == "Summer":
            return self.summer_credits or 0
        return self.max_credits if season in ("Spring", "Fall") else 0

    def limit(self, term: str) -> int:
        """The limit to warn about for a student's own plan."""
        season, _ = terms.parse(term)
        return (self.summer_credits or self.max_credits) if season == "Summer" else self.max_credits


def first_planned_term(term: str) -> str:
    return terms.at_or_after(term)


# --- Phase 1: choose courses ---------------------------------------------------------

def taken_map(graph: PrereqGraph, completed: dict[str, dict], planned: list[str],
              unverified: int) -> dict[str, dict]:
    taken = {
        code: {"code": code, "name": graph.courses[code]["name"], "credits": c["credits"],
               "grade": c["grade"]}
        for code, c in completed.items()
    }
    for code in planned:  # planned courses (and retakes) count as passed
        taken[code] = {"code": code, "name": graph.courses[code]["name"],
                       "credits": graph.courses[code]["credits_min"], "grade": None}
    if unverified > 0:
        taken[REPORTED] = {"code": REPORTED, "name": "Reported credits", "credits": unverified,
                           "grade": None}
    return taken


def evaluate_summary(tree: list[dict], taken: dict[str, dict],
                     fulfilled: frozenset[str] | set[str] = frozenset()) -> dict:
    results = evaluate(tree, taken, fulfilled)
    for node in walk(tree):
        node["progress"] = results[node["key"]]
    return summarize(tree, taken)


def choose_courses(tree, graph: PrereqGraph, rules: Rules, completed: dict[str, dict],
                   unverified: int, pinned: list[str] = (), removed: set[str] = frozenset(),
                   fulfilled: frozenset[str] | set[str] = frozenset(),
                   not_offered: set[str] = frozenset()) -> dict:
    """pinned: courses the student placed themselves (always planned).
    removed: courses the student took out (never planned).
    fulfilled: requirement keys met by verified fulfillments.
    not_offered: courses with no recent sections in the seasons being planned
    (never picked as electives; required courses are still planned)."""
    nodes = {node["key"]: node for node in walk(tree)}
    order = {key: i for i, key in enumerate(nodes)}
    add_reported_credits(tree, {}, unverified)  # lets reported credits count toward totals

    planned: list[str] = []
    retakes: set[str] = set()
    placeholders: list[dict] = []
    handled: set[str] = set()
    unplanned: list[dict] = []

    def checker_now() -> tuple[Checker, set[str]]:
        have = set(completed) | set(planned)
        unavailable = {c for c in graph.courses if rules.blocked_reason(c, have - {c})}
        unavailable |= set(removed) - set(pinned)
        # Courses no longer in the current catalog are never suggested.
        unavailable |= {c for c, info in graph.courses.items()
                        if not info.get("in_current_catalog", True)} - set(pinned)
        unavailable |= set(not_offered) - set(pinned)
        done = {code: c["grade"] for code, c in completed.items()} | {c: None for c in planned}
        return Checker(graph, done, unavailable), unavailable

    def add_with_prerequisites(code: str, checker: Checker) -> bool:
        if code in planned:
            return False
        before, same_term = checker.plan(code)
        for prereq in before + same_term:
            if prereq not in planned:
                planned.append(prereq)
                if prereq in completed:
                    retakes.add(prereq)
        planned.append(code)
        if code in completed:
            retakes.add(code)
        return True

    for code in pinned:  # the student's own choices come first
        add_with_prerequisites(code, checker_now()[0])

    for _ in range(500):  # each pass plans at least one course or settles one requirement
        summary = evaluate_summary(tree, taken_map(graph, completed, planned, unverified),
                                   fulfilled)
        units = [u for u in summary["remaining_requirements"]
                 if u["key"] not in handled and not nodes[u["key"]].get("any_course")]
        if not units:
            break
        units.sort(key=lambda u: (u["rule"] != "all_courses", order[u["key"]]))
        unit = units[0]

        checker, unavailable = checker_now()
        candidates = [c["code"] for c in unit["candidate_courses"]]

        if unit["rule"] == "all_courses":
            picks = [c for c in candidates if c not in removed]  # every listed course is required
            taken_out = [c for c in candidates if c in removed]
            if taken_out:
                unplanned.append({"key": unit["key"], "name": unit["name"],
                                  "reason": f"Required, but you removed {', '.join(taken_out)} "
                                            "from the plan"})
                handled.add(unit["key"])
        else:
            allowed = [c for c in candidates if c not in unavailable
                       and not math.isinf(checker.cost(c, unit["min_grade"]))]
            if not allowed:
                placeholders += placeholder_slots(unit)
                handled.add(unit["key"])
                continue
            # Prefer courses that also fill other remaining requirements, then
            # the fewest extra prerequisites, then fixed-credit courses.
            unit_sets = [{x["code"] for x in u["candidate_courses"]} for u in units]
            coverage = {c: sum(c in codes for codes in unit_sets) for c in allowed}
            position = {c: i for i, c in enumerate(candidates)}
            picks = [min(allowed, key=lambda c: (
                -coverage[c],
                # Prefer courses whose prerequisites are verified (curated,
                # fully parsed, or none) over ones known only as text.
                not graph.courses[c].get("prerequisites_complete", True),
                checker.cost(c, unit["min_grade"]),
                graph.courses[c]["credits_min"] != graph.courses[c]["credits_max"],
                position[c],
            ))]

        added = False
        for code in picks:
            added = add_with_prerequisites(code, checker) or added
        if not added and unit["key"] not in handled:
            # Nothing new would help (shouldn't happen); don't loop forever.
            unplanned.append({"key": unit["key"], "name": unit["name"],
                              "reason": "No combination of catalog courses found"})
            handled.add(unit["key"])

    # Fill any gap to the degree's total credits with general electives.
    summary = evaluate_summary(tree, taken_map(graph, completed, planned, unverified), fulfilled)
    counted = sum(c["credits"] for c in completed.values()) + unverified
    planned_credits = sum(graph.courses[c]["credits_min"] for c in planned if c not in retakes)
    placeholder_credits = sum(p["credits"] for p in placeholders)
    required = summary["credits"]["required"]
    gap = (required or 0) - (counted + planned_credits + placeholder_credits)
    number = 1
    while gap > 0:
        credits = min(PLACEHOLDER_CREDITS, gap)
        placeholders.append({"label": f"General elective {number}", "credits": credits,
                             "requirement": {"key": None, "name": f"{required} total credits"},
                             "kind": "elective"})
        gap -= credits
        number += 1

    return {"planned": planned, "retakes": retakes, "placeholders": placeholders,
            "unplanned": unplanned, "summary": summary, "counted_credits": counted,
            "required_credits": required}


def placeholder_slots(unit: dict) -> list[dict]:
    if unit["courses_remaining"]:
        count, credits = unit["courses_remaining"], [PLACEHOLDER_CREDITS] * unit["courses_remaining"]
    else:
        remaining = unit["credits_remaining"] or PLACEHOLDER_CREDITS
        count = math.ceil(remaining / PLACEHOLDER_CREDITS)
        credits = [PLACEHOLDER_CREDITS] * (count - 1) + [remaining - PLACEHOLDER_CREDITS * (count - 1)]
    where = " › ".join(unit["path"][1:] + [unit["name"]])
    return [{"label": f"Choose a course: {where}", "credits": credits[i],
             "requirement": {"key": unit["key"], "name": unit["name"]}, "kind": "placeholder"}
            for i in range(count)]


# --- Phase 2: schedule -----------------------------------------------------------------

@dataclass
class Item:
    id: str  # course code, or a placeholder label
    credits: int
    required: bool
    kind: str  # 'course' | 'placeholder' | 'elective'
    min_credits: int = 0  # credit standing needed before the term
    before: tuple[str, ...] = ()  # must be in an earlier term
    same_or_before: tuple[str, ...] = ()  # earlier or the same term
    seasons: frozenset[str] | None = None  # seasons it was offered recently; None = unknown


def build_items(graph: PrereqGraph, rules: Rules, completed: dict[str, dict],
                planned: list[str], placeholders: list[dict], required_codes: set[str],
                offered: dict[str, set[str]] | None = None) -> list[Item]:
    """Turn the chosen courses into graph nodes. Each unmet prerequisite group
    becomes an edge from one planned option to the course."""
    done = {code: c["grade"] for code, c in completed.items()}
    checker = Checker(graph, done)
    planned_set = set(planned)
    items = []
    for code in planned:
        before, same = [], []
        for group in graph.groups.get(code, []):
            if checker.group_met(group):
                continue
            option = next((o for o in group["options"] if o in planned_set), None)
            if option is None:
                before.append(f"missing:{'/'.join(group['options'])}")  # can never be met
                continue
            (before if group["timing"] == "before" else same).append(option)
        seasons = frozenset(offered[code]) if offered and code in offered else None
        items.append(Item(code, graph.courses[code]["credits_min"], code in required_codes,
                          "course", rules.min_credits(code), tuple(before), tuple(same), seasons))
    for p in placeholders:
        items.append(Item(p["label"], p["credits"], p["kind"] == "placeholder", p["kind"]))
    return items


def topological_order(items: list[Item]) -> tuple[list[str], set[str]]:
    """Kahn's algorithm. Returns (order, ids stuck in or behind a cycle)."""
    ids = {item.id for item in items}
    preds = {item.id: {p for p in item.before + item.same_or_before if p in ids} for item in items}
    succs = {i: set() for i in ids}
    for item_id, ps in preds.items():
        for p in ps:
            succs[p].add(item_id)
    indegree = {i: len(ps) for i, ps in preds.items()}
    queue = sorted(i for i, d in indegree.items() if d == 0)
    order = []
    while queue:
        node = queue.pop(0)
        order.append(node)
        for s in sorted(succs[node]):
            indegree[s] -= 1
            if indegree[s] == 0:
                queue.append(s)
    return order, ids - set(order)


def chain_lengths(items: list[Item], order: list[str]) -> dict[str, int]:
    """Number of terms in the longest chain starting at each item (critical path)."""
    ids = {item.id for item in items}
    succs = {i: [] for i in ids}
    for item in items:
        for p in item.before:
            if p in ids:
                succs[p].append((item.id, 1))
        for p in item.same_or_before:
            if p in ids:
                succs[p].append((item.id, 0))
    length = {}
    for node in reversed(order):
        length[node] = 1 + max((length[s] - 1 + step for s, step in succs[node]), default=0)
    return length


def schedule(items: list[Item], start_term: str, calendar: Calendar, earned: int,
             pinned: dict[str, str] = None) -> dict:
    """Place items in terms from `start_term` on, using the calendar's seasons
    and credit limits. pinned: item id -> term the student chose; those are
    placed as-is (check_plan reports problems) and everything else is
    scheduled around them. A course with offering history is only placed in a
    season it was offered in."""
    pinned = pinned or {}
    seasons = tuple(dict.fromkeys(
        calendar.seasons + tuple(terms.parse(t)[0] for t in pinned.values())))
    order, cyclic = topological_order(items)
    by_id = {item.id: item for item in items}
    chain = chain_lengths(items, order)
    rank = {item.id: i for i, item in enumerate(items)}  # planning order breaks ties
    biggest = max(calendar.capacity(f"{season} 2000") for season in calendar.seasons)

    unscheduled = []
    for item_id in sorted(cyclic):
        unscheduled.append((item_id, "Circular prerequisites"))
    for item in items:
        if item.id in pinned:
            continue
        if any(p.startswith("missing:") for p in item.before):
            unscheduled.append((item.id, "A prerequisite can't be planned"))
        elif item.credits > biggest:
            unscheduled.append((item.id, f"{item.credits} credits exceeds your credit limit"))
        elif item.seasons is not None and not item.seasons & set(calendar.seasons):
            unscheduled.append((item.id, "Only offered recently in "
                                + ", ".join(sorted(item.seasons)) + ", which isn't in your plan"))
    blocked = {item_id for item_id, _ in unscheduled}

    def depends_on_blocked(item: Item, seen=()) -> bool:
        return any(p in blocked or (p in by_id and p not in seen
                                    and depends_on_blocked(by_id[p], seen + (item.id,)))
                   for p in item.before + item.same_or_before)

    for item in items:
        if item.id not in blocked and item.id not in pinned and depends_on_blocked(item):
            unscheduled.append((item.id, "Depends on a course that can't be scheduled"))
    blocked = {item_id for item_id, _ in unscheduled}

    def priority(item: Item):
        kind_order = {"course": 0, "placeholder": 1, "elective": 2}[item.kind]
        return (-chain[item.id], not item.required, kind_order, rank[item.id])

    # Lower bound on terms: enough capacity for every credit, and the longest chain.
    first = terms.at_or_after(start_term, seasons)
    total = sum(item.credits for item in items if item.id not in blocked)
    by_capacity, room, t = 0, 0, first
    while room < total and by_capacity < MAX_TERMS:
        if calendar.capacity(t):
            by_capacity += 1
            room += calendar.capacity(t)
        t = terms.next_term(t, calendar.seasons)
    lower_bound = max(by_capacity,
                      max((chain[i.id] for i in items if i.id not in blocked), default=0))
    last_pin = max((terms.ordinal(t) for t in pinned.values()), default=-1)
    horizon = min(lower_bound * 2 + EXTRA_TERMS, MAX_TERMS)

    term_of: dict[str, int] = {item_id: terms.ordinal(t) for item_id, t in pinned.items()}
    planned_terms = []
    term = first
    idle = 0  # terms in a row where nothing could be placed
    remaining = [item for item in items if item.id not in blocked and item.id not in pinned]
    while (remaining or terms.ordinal(term) <= last_pin) and len(planned_terms) < horizon:
        here = terms.ordinal(term)
        season = terms.parse(term)[0]
        chosen = [item for item in items if pinned.get(item.id) == term]
        used = sum(item.credits for item in chosen)
        capacity = calendar.capacity(term)
        progress = True
        while progress:  # repeat so same-term corequisites can join
            progress = False
            ready = [
                item for item in remaining
                if item.id not in term_of
                and all(term_of.get(p, math.inf) < here for p in item.before)
                and all(term_of.get(p, math.inf) <= here for p in item.same_or_before)
                and earned >= item.min_credits
                and (item.seasons is None or season in item.seasons)
            ]
            for item in sorted(ready, key=priority):
                if used + item.credits <= capacity:
                    term_of[item.id] = here
                    chosen.append(item)
                    used += item.credits
                    progress = True
                    break  # re-check readiness after each addition
        if chosen:
            planned_terms.append({"term": term, "items": chosen, "credits": used})
            earned += used
            idle = 0
        else:
            idle += 1
            if idle > len(seasons) * 2 and here >= last_pin:
                break  # nothing can move forward
        remaining = [item for item in remaining if item.id not in term_of]
        term = terms.next_term(term, seasons)

    for item in remaining:
        reason = ("Beyond the planning horizon" if len(planned_terms) >= horizon
                  else "Credit standing, prerequisites, or offerings can't be met")
        unscheduled.append((item.id, reason))
    return {"terms": planned_terms, "unscheduled": unscheduled, "lower_bound_terms": lower_bound}


def check_plan(plan_terms: list[dict], graph: PrereqGraph, rules: Rules,
               completed: dict[str, dict], limit, earned: int
               ) -> tuple[dict[int, list[str]], dict[str, list[str]]]:
    """Check a plan against the rules. The scheduler never breaks them, but
    courses the student placed by hand can. `plan_terms` are in order; `limit`
    is a credit limit, or a function giving one per term. Returns (warnings by
    term index, warnings by course code)."""
    limit_for = limit if callable(limit) else (lambda term: limit)
    checker = Checker(graph, {code: c["grade"] for code, c in completed.items()})
    index_of = {item.id: i for i, t in enumerate(plan_terms) for item in t["items"]}
    term_name = {i: t["term"] for i, t in enumerate(plan_terms)}
    term_warnings: dict[int, list[str]] = {}
    course_warnings: dict[str, list[str]] = {}

    for i, t in enumerate(plan_terms):
        if t["credits"] > limit_for(t["term"]):
            term_warnings.setdefault(i, []).append(
                f"{t['credits']} credits is over your {limit_for(t['term'])}-credit limit.")
        for item in t["items"]:
            if item.kind != "course":
                continue
            warns = course_warnings.setdefault(item.id, [])
            if earned < item.min_credits:
                warns.append(f"Requires {item.min_credits} earned credits; you'll have about "
                             f"{earned} by {t['term']}.")
            for group in graph.groups.get(item.id, []):
                if checker.group_met(group):
                    continue
                same_ok = group["timing"] != "before"
                planned = [o for o in group["options"] if o in index_of]
                if any(index_of[o] < i or (same_ok and index_of[o] == i) for o in planned):
                    continue
                needed = " or ".join(group["options"])
                when = "in the same semester or earlier" if same_ok else "first"
                if planned:
                    soonest = min(planned, key=lambda o: index_of[o])
                    warns.append(f"Needs {needed} {when}, but {soonest} is planned for "
                                 f"{term_name[index_of[soonest]]}.")
                else:
                    warns.append(f"Needs {needed} {when}, and it isn't in your plan.")
        earned += t["credits"]
    return term_warnings, {k: v for k, v in course_warnings.items() if v}


# --- Whole plan ----------------------------------------------------------------------

def build_plan(tree, graph: PrereqGraph, rules: Rules, completed: dict[str, dict],
               unverified: int, start_term: str, max_credits: "int | Calendar",
               pinned: dict[str, str] = None, removed: set[str] = frozenset(),
               fulfilled: frozenset[str] | set[str] = frozenset(),
               offered: dict[str, set[str]] | None = None,
               target_term: str | None = None) -> dict:
    """completed: code -> {"grade", "credits"} (include courses in progress).
    unverified: verified credit with no specific course (counts toward totals only).
    max_credits: a per-term limit, or a Calendar (Summer and its limit).
    pinned: code -> term the student placed it in. removed: codes they took out.
    fulfilled: requirement keys met by verified fulfillments.
    offered: code -> seasons it had sections in recently; None if no offering data.
    target_term: the student's desired graduation term, if any."""
    pinned = pinned or {}
    calendar = max_credits if isinstance(max_credits, Calendar) else Calendar(max_credits)
    start = terms.at_or_after(start_term, calendar.seasons)
    not_offered = set()
    if offered is not None:
        not_offered = {c for c in graph.courses
                       if not offered.get(c, set()) & set(calendar.seasons)}
    chosen = choose_courses(tree, graph, rules, completed, unverified, list(pinned), removed,
                            fulfilled, not_offered)
    planned, placeholders = chosen["planned"], chosen["placeholders"]

    # Which requirement(s) each planned course fills, from the final evaluation.
    summary = chosen["summary"]
    fills: dict[str, list[dict]] = {}
    required_codes = set()
    for unit in summary["completed_requirements"] + summary["remaining_requirements"]:
        for course in unit["applied_courses"]:
            if course["code"] in planned:
                fills.setdefault(course["code"], []).append(
                    {"key": unit["key"], "name": unit["name"], "category": unit["category"]})
                if unit["rule"] == "all_courses":
                    required_codes.add(course["code"])

    items = build_items(graph, rules, completed, planned, placeholders, required_codes, offered)
    result = schedule(items, start, calendar, chosen["counted_credits"], pinned)
    term_warnings, course_warnings = check_plan(result["terms"], graph, rules, completed,
                                                calendar.limit, chosen["counted_credits"])
    needed_by: dict[str, list[str]] = {}
    for item in items:
        for p in item.before + item.same_or_before:
            needed_by.setdefault(p, []).append(item.id)

    placeholder_by_label = {p["label"]: p for p in placeholders}

    def describe(item: Item) -> dict:
        if item.kind != "course":
            p = placeholder_by_label[item.id]
            return {"code": None, "name": item.id, "credits": item.credits, "kind": item.kind,
                    "required": item.required, "retake": False,
                    "satisfies": [{**p["requirement"], "category": None}],
                    "reasons": [f"Fills: {p['requirement']['name']}"],
                    "uncertain": ["You choose the course."],
                    "prerequisites": [], "notes": [], "pinned": False, "warnings": []}
        course = graph.courses[item.id]
        notes = rules.notes(item.id)
        uncertain = []
        if not course["prerequisites_complete"] and course.get("prerequisite_text"):
            notes.append(f"Also check prerequisites: {course['prerequisite_text']}")
            uncertain.append("Prerequisites are only available as catalog text and weren't checked.")
        if offered is not None:
            if item.seasons:
                notes.append("Offered recently in " + ", ".join(
                    s for s in terms.SEASONS if s in item.seasons) + " (Testudo).")
            else:
                uncertain.append("No sections in the recent terms checked on Testudo; "
                                 "check that it's still offered.")
        else:
            uncertain.append("Offering schedule not checked.")
        fills_here = fills.get(item.id, [])
        reasons = [f"Fills: {f['name']}" for f in fills_here]
        later = needed_by.get(item.id, [])
        if later:
            reasons.append("Needed before " + ", ".join(sorted(later)))
        prereqs = [p for p in item.before + item.same_or_before if not p.startswith("missing:")]
        return {"code": item.id, "name": course["name"], "credits": item.credits,
                "kind": "course", "required": item.required,
                "retake": item.id in chosen["retakes"],
                "satisfies": fills_here or [{"key": None,
                                             "name": "Prerequisite for a later course",
                                             "category": None}],
                "reasons": reasons, "uncertain": uncertain,
                "prerequisites": prereqs, "notes": notes,
                "pinned": item.id in pinned, "warnings": course_warnings.get(item.id, [])}

    plan_terms = [{"term": t["term"], "credits": t["credits"], "warnings": term_warnings.get(i, []),
              "courses": [describe(item) for item in t["items"]]} for i, t in enumerate(result["terms"])]
    while plan_terms and not plan_terms[-1]["courses"]:
        plan_terms.pop()
    by_id = {item.id: item for item in items}
    unscheduled = [{**describe(by_id[i]), "reason": reason} for i, reason in result["unscheduled"]]

    planned_credits = sum(c["credits"] for t in plan_terms for c in t["courses"] if not c["retake"])
    complete = not unscheduled and not chosen["unplanned"]
    graduation = plan_terms[-1]["term"] if plan_terms and complete else None
    warnings = [{"term": t["term"], "code": None, "message": w}
                for t in plan_terms for w in t["warnings"]]
    warnings += [{"term": t["term"], "code": c["code"], "message": w}
                 for t in plan_terms for c in t["courses"] for w in c["warnings"]]
    if not plan_terms and complete:
        graduation_note = "Every tracked requirement is already met."
    elif graduation and warnings:
        graduation_note = "Your changes break some rules. See the warnings before relying on this date."
    elif graduation and pinned:
        graduation_note = "Based on your changes; everything else was planned around them."
    elif graduation:
        earliest = len(plan_terms) == result["lower_bound_terms"]
        graduation_note = (
            "Earliest possible under these assumptions: the plan needs as many semesters as "
            "the credit limit and the longest prerequisite chain require."
            if earliest else
            f"At least {result['lower_bound_terms']} semesters are needed; this plan uses "
            f"{len(plan_terms)} because of credit-standing or prerequisite timing."
        )
    else:
        graduation_note = "Some courses or requirements couldn't be planned (see below)."

    assumptions = [
        ("Courses are placed only in seasons they had sections in recently on Testudo; "
         "courses without recent sections may not be offered." if offered is not None else
         "Course offerings weren't checked: every course is assumed to run every term."),
        "Seats, times, and permissions aren't known.",
        ("Summer terms are used, up to " + str(calendar.summer_credits) + " credits."
         if calendar.summer_credits else "Summer and Winter terms aren't used."),
        f"\"Choose a course\" slots and general electives are assumed to be "
        f"{PLACEHOLDER_CREDITS} credits.",
        "Planned courses are assumed to be passed with the minimum grade required.",
    ]
    target = None
    if target_term:
        if graduation is None:
            message = "A graduation term can't be projected yet, so the target can't be checked."
            meets = None
        elif terms.ordinal(graduation) <= terms.ordinal(target_term):
            message, meets = f"Finishes by your target of {target_term}.", True
        else:
            message, meets = (f"Finishes in {graduation}, after your target of {target_term}. "
                              "More credits per semester or Summer terms could help."), False
        target = {"term": target_term, "meets": meets, "message": message}

    return {
        "disclaimer": DISCLAIMER,
        "start_term": start,
        "max_credits_per_term": calendar.max_credits,
        "target": target,
        "projected_graduation": graduation,
        "graduation_note": graduation_note,
        "warnings": warnings,
        "pinned": [{"code": code, "term": term} for code, term in pinned.items()],
        "removed": sorted(removed),
        "credits": {
            "remaining": max((chosen["required_credits"] or 0) - chosen["counted_credits"], 0),
            "completed": chosen["counted_credits"],
            "planned": planned_credits,
            "total": chosen["counted_credits"] + planned_credits,
            "required": chosen["required_credits"],
        },
        "terms": plan_terms,
        "unscheduled": unscheduled,
        "unplanned_requirements": chosen["unplanned"],
        "not_checked": [{"key": u["key"], "name": u["name"]}
                        for u in summary["untracked_requirements"]],
        "assumptions": assumptions,
    }
