"""The student's own semester plan, and optional recommendations.

The saved plan is the planned_courses table: one row per course, with its
semester and credits. Every number shown (semester credits, planned credits,
credits remaining) is computed from those rows on each request, so it always
matches what's saved.

A recommendation is generated by app/planner.py around the courses the
student already planned. It isn't saved unless the student accepts it.
"""

from datetime import date
from uuid import UUID

from fastapi import APIRouter, HTTPException
from pydantic import BaseModel, Field

from app.courses import normalize_code
from app.db import get_connection
from app.degree_progress import add_reported_credits, summarize
from app.evaluator import evaluate, walk
from app.planner import (
    DISCLAIMER,
    Item,
    build_plan,
    check_plan,
    first_planned_term,
    terms_after,
)
from app.prerequisites import Checker, load_graph
from app.requirements import find_program, load_requirements
from app.restrictions import load_rules
from app.sessions import load_session

router = APIRouter(prefix="/api/sessions", tags=["graduation plan"])

TERM_PATTERN = r"^(Spring|Fall) \d{4}$"


# --- Response models ---------------------------------------------------------------

class RequirementRef(BaseModel):
    key: str | None
    name: str
    category: str | None


class PlannedCourse(BaseModel):
    code: str
    name: str
    credits: int  # credits this course counts for in the plan
    credits_min: int
    credits_max: int
    retake: bool  # completed before with too low a grade; doesn't add credits again
    satisfies: list[RequirementRef]  # degree requirements this fills
    prerequisites: list[str]  # planned courses this depends on
    notes: list[str]  # restrictions and conditions to check
    warnings: list[str]  # rules this placement breaks


class PlannedTerm(BaseModel):
    term: str
    credits: int  # sum of this semester's courses
    warnings: list[str]  # e.g. over the credit limit
    courses: list[PlannedCourse]


class PlanWarning(BaseModel):
    term: str
    code: str | None
    message: str


class StillNeeded(BaseModel):
    key: str
    name: str
    path: list[str]
    courses_remaining: int | None
    credits_remaining: int | None


class PlanCredits(BaseModel):
    completed: int  # from completed courses plus reported credits
    planned: int  # new credits in the plan (retakes don't add credits)
    total: int  # completed + planned
    required: int | None  # degree total
    remaining: int | None  # still to plan: required - total


class NotChecked(BaseModel):
    key: str
    name: str


class StudentPlan(BaseModel):
    program_name: str
    requirements_verified: bool  # False: no verified major requirements yet
    current_term: str  # earliest semester courses can be planned in
    max_credits_per_term: int
    projected_graduation: str | None
    graduation_note: str
    credits: PlanCredits
    terms: list[PlannedTerm]  # semesters that have courses, in order
    warnings: list[PlanWarning]
    still_needed: list[StillNeeded]  # requirements not covered by completed + planned courses
    not_checked: list[NotChecked]  # e.g. GPA, residency


class RecommendedCourse(BaseModel):
    code: str | None  # None for a "choose a course" slot or general elective
    name: str
    credits: int
    term: str
    satisfies: list[RequirementRef]


class Recommendation(BaseModel):
    disclaimer: str
    projected_graduation: str | None
    graduation_note: str
    additions: list[RecommendedCourse]  # courses to add to the plan
    slots: list[RecommendedCourse]  # requirements needing a course you choose
    unscheduled: list[str]  # couldn't be placed (reasons)
    assumptions: list[str]


class PlannedCourseIn(BaseModel):
    code: str = Field(max_length=10)
    term: str = Field(pattern=TERM_PATTERN)
    credits: int | None = Field(None, description="Only for variable-credit courses")


class PlannedCourseUpdate(BaseModel):
    term: str | None = Field(None, pattern=TERM_PATTERN)
    credits: int | None = None


class AcceptRecommendation(BaseModel):
    courses: list[PlannedCourseIn] = Field(max_length=100)


# --- Routes ---------------------------------------------------------------------------

@router.get("/{session_id}/plan", response_model=StudentPlan)
def get_plan(session_id: UUID):
    with get_connection() as conn:
        return plan_response(conn, session_id)


@router.post("/{session_id}/plan/courses", response_model=StudentPlan, status_code=201)
def add_planned_course(session_id: UUID, body: PlannedCourseIn):
    with get_connection() as conn:
        context = load_context(conn, session_id)
        insert_planned(conn, context, body)
        return plan_response(conn, session_id)


@router.patch("/{session_id}/plan/courses/{course_code}", response_model=StudentPlan)
def update_planned_course(session_id: UUID, course_code: str, body: PlannedCourseUpdate):
    """Move a course to another semester, or change its credits."""
    changes = body.model_dump(exclude_unset=True)
    with get_connection() as conn:
        context = load_context(conn, session_id)
        code = normalize_code(course_code)
        row = next((p for p in context["planned"] if p["code"] == code), None)
        if row is None:
            raise HTTPException(status_code=404, detail=f"{code} isn't in your plan")
        if changes.get("term"):
            check_term(context, changes["term"])
        if "credits" in changes:
            changes["credits"] = check_credits(context, code, changes["credits"])
        if changes:
            columns = ", ".join(f"{column} = %({column})s" for column in changes)
            conn.execute(
                f"UPDATE planned_courses SET {columns} WHERE session_id = %(session)s "
                "AND course_id = %(course)s",
                {**changes, "session": session_id, "course": row["course_id"]},
            )
        return plan_response(conn, session_id)


@router.delete("/{session_id}/plan/courses/{course_code}", response_model=StudentPlan)
def remove_planned_course(session_id: UUID, course_code: str):
    with get_connection() as conn:
        context = load_context(conn, session_id)
        code = normalize_code(course_code)
        row = next((p for p in context["planned"] if p["code"] == code), None)
        if row is None:
            raise HTTPException(status_code=404, detail=f"{code} isn't in your plan")
        conn.execute("DELETE FROM planned_courses WHERE session_id = %s AND course_id = %s",
                     (session_id, row["course_id"]))
        return plan_response(conn, session_id)


@router.delete("/{session_id}/plan", response_model=StudentPlan)
def clear_plan(session_id: UUID):
    with get_connection() as conn:
        load_session(conn, session_id)
        conn.execute("DELETE FROM planned_courses WHERE session_id = %s", (session_id,))
        return plan_response(conn, session_id)


@router.post("/{session_id}/plan/recommendation", response_model=Recommendation)
def recommend(session_id: UUID):
    """A recommended plan built around the courses already in the student's plan.
    Nothing is saved; accept it with POST .../plan/recommendation/accept."""
    with get_connection() as conn:
        context = load_context(conn, session_id)
    if context["program"]["requirements_status"] != "verified":
        raise HTTPException(status_code=409, detail=(
            f"Finish Line doesn't have verified requirements for {context['program']['name']} "
            "yet, so it can't recommend a plan. You can still plan courses yourself."))
    return make_recommendation(context)


@router.post("/{session_id}/plan/recommendation/accept", response_model=StudentPlan)
def accept_recommendation(session_id: UUID, body: AcceptRecommendation):
    """Add the courses the student reviewed (from a recommendation) to their plan."""
    with get_connection() as conn:
        context = load_context(conn, session_id)
        for course in body.courses:
            insert_planned(conn, context, course)
            context["planned"].append({"code": normalize_code(course.code)})
        return plan_response(conn, session_id)


# --- Loading and validation ------------------------------------------------------------

def load_context(conn, session_id: UUID) -> dict:
    session = load_session(conn, session_id)
    program = find_program(conn, session["program_slug"])
    tree, _ = load_requirements(conn, program)
    planned = conn.execute(
        """
        SELECT p.course_id, c.code, p.term, p.credits FROM planned_courses p
        JOIN courses c ON c.id = p.course_id
        WHERE p.session_id = %s ORDER BY p.added_at, c.code
        """,
        (session_id,),
    ).fetchall()
    return {"session": session, "program": program, "tree": tree, "planned": planned,
            "graph": load_graph(conn, program["university_id"]),
            "rules": load_rules(conn, program)}


def current_term(context: dict) -> str:
    return first_planned_term(context["session"]["current_term"] or default_term())


def check_term(context: dict, term: str) -> None:
    start = current_term(context)
    if terms_after(start, term) < 0:
        raise HTTPException(status_code=422, detail=(
            f"{term} is before {start}. Add courses you've already taken as completed courses "
            "in your profile."))


def check_credits(context: dict, code: str, credits: int | None) -> int:
    course = context["graph"].courses[code]
    if credits is None:
        return course["credits_min"]
    if not course["credits_min"] <= credits <= course["credits_max"]:
        raise HTTPException(status_code=422, detail=(
            f"{code} is {course['credits_min']}-{course['credits_max']} credits"))
    return credits


def insert_planned(conn, context: dict, body: PlannedCourseIn) -> None:
    code = normalize_code(body.code)
    if code not in context["graph"].courses:
        raise HTTPException(status_code=404, detail=f"Course {code} not found")
    if any(p["code"] == code for p in context["planned"]):
        raise HTTPException(status_code=409, detail=f"{code} is already in your plan")
    completed = {c["code"]: c["grade"] for c in context["session"]["courses"]}
    if code in completed and completed[code] not in ("D+", "D", "D-", "F"):
        raise HTTPException(status_code=409, detail=f"You've already completed {code}")
    check_term(context, body.term)
    credits = check_credits(context, code, body.credits)
    conn.execute(
        """
        INSERT INTO planned_courses (session_id, course_id, term, credits)
        SELECT %s, id, %s, %s FROM courses WHERE code = %s AND university_id = %s
        """,
        (context["session"]["id"], body.term, credits, code,
         context["program"]["university_id"]),
    )


def plan_response(conn, session_id: UUID) -> dict:
    return build_student_plan(load_context(conn, session_id))


def completed_courses(session: dict) -> dict[str, dict]:
    return {c["code"]: {"grade": c["grade"], "credits": c["credits"]} for c in session["courses"]}


# --- The plan view (pure: everything derived from the saved rows) ------------------------

def build_student_plan(context: dict) -> dict:
    session, program = context["session"], context["program"]
    graph, rules, tree = context["graph"], context["rules"], context["tree"]
    completed = completed_courses(session)
    unverified = session["credits"]["unmatched"]
    planned = context["planned"]
    verified = program["requirements_status"] == "verified"

    # Semesters, in order, each with the credits of the courses saved in it.
    order = sorted({p["term"] for p in planned}, key=lambda t: terms_after("Spring 2000", t))
    terms = [{"term": term,
              "items": [Item(p["code"], p["credits"], False, "course",
                             rules.min_credits(p["code"]))
                        for p in planned if p["term"] == term]}
             for term in order]
    for t in terms:
        t["credits"] = sum(item.credits for item in t["items"])

    counted = sum(c["credits"] for c in completed.values()) + unverified
    term_warnings, course_warnings = check_plan(terms, graph, rules, completed,
                                                session["max_credits_per_term"], counted)

    # Requirement coverage from completed + planned courses.
    taken = {code: {"code": code, "name": graph.courses[code]["name"], "credits": c["credits"],
                    "grade": c["grade"]} for code, c in completed.items()}
    for p in planned:
        taken[p["code"]] = {"code": p["code"], "name": graph.courses[p["code"]]["name"],
                            "credits": p["credits"], "grade": None}
    add_reported_credits(tree, taken, unverified)
    results = evaluate(tree, taken)
    for node in walk(tree):
        node["progress"] = results[node["key"]]
    summary = summarize(tree, taken)
    fills: dict[str, list[dict]] = {}
    for unit in summary["completed_requirements"] + summary["remaining_requirements"]:
        for course in unit["applied_courses"]:
            fills.setdefault(course["code"], []).append(
                {"key": unit["key"], "name": unit["name"], "category": unit["category"]})

    checker = Checker(graph, {code: c["grade"] for code, c in completed.items()})
    planned_codes = {p["code"] for p in planned}
    have = set(completed) | planned_codes
    retakes = {p["code"] for p in planned if p["code"] in completed}

    def describe(item: Item) -> dict:
        course = graph.courses[item.id]
        warnings = list(course_warnings.get(item.id, []))
        reason = rules.blocked_reason(item.id, have - {item.id}, elective=False)
        if reason:
            warnings.append(reason + ".")
        if not course.get("in_current_catalog", True):
            warnings.append("Not in the current UMD catalog.")
        notes = rules.notes(item.id)
        if not course["prerequisites_complete"] and course.get("prerequisite_text"):
            notes.append(f"Also check prerequisites: {course['prerequisite_text']}")
        satisfies = fills.get(item.id) or [
            {"key": None, "name": "Doesn't fill a remaining requirement", "category": None}]
        prerequisites = sorted({o for g in graph.groups.get(item.id, [])
                                if not checker.group_met(g)
                                for o in g["options"] if o in planned_codes})
        return {"code": item.id, "name": course["name"], "credits": item.credits,
                "credits_min": course["credits_min"], "credits_max": course["credits_max"],
                "retake": item.id in retakes, "satisfies": satisfies,
                "prerequisites": prerequisites, "notes": notes, "warnings": warnings}

    out_terms = [{"term": t["term"], "credits": t["credits"],
                  "warnings": term_warnings.get(i, []),
                  "courses": [describe(item) for item in t["items"]]}
                 for i, t in enumerate(terms)]
    warnings = [{"term": t["term"], "code": None, "message": w}
                for t in out_terms for w in t["warnings"]]
    warnings += [{"term": t["term"], "code": c["code"], "message": w}
                 for t in out_terms for c in t["courses"] for w in c["warnings"]]

    planned_credits = sum(p["credits"] for p in planned if p["code"] not in retakes)
    required = summary["credits"]["required"]
    total = counted + planned_credits
    still_needed = [
        {k: u[k] for k in ("key", "name", "path", "courses_remaining", "credits_remaining")}
        for u in summary["remaining_requirements"]
    ]

    if not verified:
        graduation, note = None, (
            f"Finish Line doesn't have verified requirements for {program['name']} yet, so it "
            "can't tell when this plan would finish the major. University and Gen Ed "
            "requirements are still checked.")
    elif not planned:
        graduation, note = None, ("Your plan is empty. Add courses to semesters, or generate a "
                                  "recommended plan to start from.")
    elif still_needed:
        graduation, note = None, (
            (f"{len(still_needed)} requirements still need" if len(still_needed) != 1
             else "1 requirement still needs") + " courses: " + ", ".join(u["name"] for u in still_needed[:4])
            + ("…" if len(still_needed) > 4 else "") + ".")
    else:
        graduation = out_terms[-1]["term"]
        note = ("Your plan completes every tracked requirement"
                + (", but it has problems to fix first." if warnings else "."))

    return {
        "program_name": program["name"],
        "requirements_verified": verified,
        "current_term": current_term(context),
        "max_credits_per_term": session["max_credits_per_term"],
        "projected_graduation": graduation,
        "graduation_note": note,
        "credits": {"completed": counted, "planned": planned_credits, "total": total,
                    "required": required,
                    "remaining": max(required - total, 0) if required is not None else None},
        "terms": out_terms,
        "warnings": warnings,
        "still_needed": still_needed,
        "not_checked": [{"key": u["key"], "name": u["name"]}
                        for u in summary["untracked_requirements"]],
    }


def make_recommendation(context: dict) -> dict:
    session = context["session"]
    pinned = {p["code"]: p["term"] for p in context["planned"]}
    plan = build_plan(context["tree"], context["graph"], context["rules"],
                      completed_courses(session), session["credits"]["unmatched"],
                      current_term(context), session["max_credits_per_term"], pinned)
    additions, slots = [], []
    for t in plan["terms"]:
        for c in t["courses"]:
            course = {"code": c["code"], "name": c["name"], "credits": c["credits"],
                      "term": t["term"], "satisfies": c["satisfies"]}
            if c["code"] is None:
                slots.append(course)
            elif c["code"] not in pinned:
                additions.append(course)
    return {
        "disclaimer": DISCLAIMER,
        "projected_graduation": plan["projected_graduation"],
        "graduation_note": plan["graduation_note"],
        "additions": additions,
        "slots": slots,
        "unscheduled": [f"{u['code'] or u['name']}: {u['reason']}" for u in plan["unscheduled"]]
        + [f"{r['name']}: {r['reason']}" for r in plan["unplanned_requirements"]],
        "assumptions": plan["assumptions"],
    }


def default_term() -> str:
    today = date.today()
    season = "Spring" if today.month <= 5 else "Fall"
    return f"{season} {today.year}"
