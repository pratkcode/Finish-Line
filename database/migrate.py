"""Apply database migrations, then sync catalog and degree data.

Usage (from the project root):
    backend/.venv/bin/python database/migrate.py            # migrations + data sync
    backend/.venv/bin/python database/migrate.py --schema-only

- Migrations in database/migrations/ run in order, once each, each in its own
  transaction, and are recorded in schema_migrations.
- A database created before migrations existed (from the old schema.sql) is
  detected and recorded as having applied 001 without re-running it.
- The data sync (seed.sql, generated by build_seed.py) updates courses by
  code and rebuilds derived tables. It never deletes courses, so planning
  sessions and completed courses are preserved.

Reads DATABASE_URL from the environment or backend/.env.
"""

import argparse
import os
import sys
from pathlib import Path

import psycopg

ROOT = Path(__file__).resolve().parent.parent
MIGRATIONS = ROOT / "database" / "migrations"
SEED = ROOT / "database" / "seed.sql"


def database_url() -> str:
    if os.getenv("DATABASE_URL"):
        return os.environ["DATABASE_URL"]
    env = ROOT / "backend" / ".env"
    if env.exists():
        for line in env.read_text().splitlines():
            if line.startswith("DATABASE_URL="):
                return line.split("=", 1)[1].strip()
    return "postgresql://localhost:5432/finish_line"


def migrate(conn) -> list[str]:
    conn.execute("""
        CREATE TABLE IF NOT EXISTS schema_migrations (
            version    TEXT PRIMARY KEY,
            applied_at TIMESTAMPTZ NOT NULL DEFAULT now()
        )""")
    applied = {row[0] for row in conn.execute("SELECT version FROM schema_migrations")}
    if not applied and conn.execute("SELECT to_regclass('public.courses')").fetchone()[0]:
        # Created from the pre-migration schema.sql: that schema is 001.
        conn.execute("INSERT INTO schema_migrations (version) VALUES ('001')")
        applied.add("001")
        print("Existing database detected: recorded 001 as applied")
    conn.commit()

    ran = []
    for path in sorted(MIGRATIONS.glob("*.sql")):
        version = path.name.split("_", 1)[0]
        if version in applied:
            continue
        with conn.transaction():
            conn.execute(path.read_text())
            conn.execute("INSERT INTO schema_migrations (version) VALUES (%s)", (version,))
        ran.append(path.name)
        print(f"Applied {path.name}")
    return ran


def sync_data(conn) -> None:
    if not SEED.exists():
        sys.exit("database/seed.sql is missing: run python3 database/build_seed.py first")
    conn.execute(SEED.read_text())  # seed.sql manages its own transaction
    conn.commit()
    print("Synced catalog and degree data")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--schema-only", action="store_true")
    args = parser.parse_args()
    with psycopg.connect(database_url()) as conn:
        ran = migrate(conn)
        if not ran:
            print("Schema is up to date")
        if not args.schema_only:
            sync_data(conn)


if __name__ == "__main__":
    main()
